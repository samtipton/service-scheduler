"""Postgres dump of the live roster for compare_objectives --dump.

Writes users, services, tasks, prefs, schedules, and the last year of
assignments to live.sql. Names, emails, and passwords are replaced so the
file is safe to commit. Load it into the throwaway test database. History
is Assignment rows; is_official is unused.
"""

from datetime import date
from io import StringIO
from pathlib import Path

from django.contrib.auth import get_user_model
from django.db import connection
from django.utils import timezone

from schedules.models import (
    Assignment,
    Schedule,
    Service,
    Task,
    TaskPreference,
    TaskRequires,
)
from schedules.services.fairness import add_months

COMPARE_FIXTURE_DIR = Path(__file__).resolve().parent.parent / "fixtures" / "compare"
LIVE_DUMP_PATH = COMPARE_FIXTURE_DIR / "live.sql"


def assignment_cutoff(months: int = 12, today: date | None = None) -> date:
    today = today or timezone.localdate()
    return add_months(today.year, today.month, -months)


def _quote_ident(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def _table_columns(cursor, table: str) -> list[str]:
    cursor.execute(f"SELECT * FROM {_quote_ident(table)} LIMIT 0")
    return [col[0] for col in cursor.description]


def _copy_select(cursor, table: str, columns: list[str], where_sql: str = "") -> str:
    col_sql = ", ".join(_quote_ident(c) for c in columns)
    query = f"SELECT {col_sql} FROM {_quote_ident(table)} {where_sql}"
    buf = StringIO()
    cursor.copy_expert(f"COPY ({query}) TO STDOUT", buf)
    return buf.getvalue()


def _write_copy(out, table: str, columns: list[str], data: str):
    col_sql = ", ".join(_quote_ident(c) for c in columns)
    out.write(f"COPY {_quote_ident(table)} ({col_sql}) FROM stdin;\n")
    out.write(data)
    if data and not data.endswith("\n"):
        out.write("\n")
    out.write("\\.\n\n")


def _serial_columns(cursor, table: str) -> list[str]:
    serials = []
    for col in _table_columns(cursor, table):
        cursor.execute("SELECT pg_get_serial_sequence(%s, %s)", [table, col])
        if cursor.fetchone()[0]:
            serials.append(col)
    return serials


USER_ANON_EXPR = {
    "password": "'!'",
    "last_login": "NULL",
    "username": "'Person ' || id::text",
    "email": "'person' || id::text || '@example.com'",
    "first_name": "'Person'",
    "last_name": "lpad(id::text, 3, '0')",
}


def _full_tables() -> list[str]:
    return [
        get_user_model()._meta.db_table,
        Service._meta.db_table,
        Task._meta.db_table,
        Task.excludes.through._meta.db_table,
        TaskPreference._meta.db_table,
        TaskRequires._meta.db_table,
        Schedule._meta.db_table,
    ]


def _user_copy(cursor) -> tuple[list[str], str]:
    table = get_user_model()._meta.db_table
    columns = _table_columns(cursor, table)
    exprs = ", ".join(USER_ANON_EXPR.get(col, _quote_ident(col)) for col in columns)
    buf = StringIO()
    cursor.copy_expert(
        f"COPY (SELECT {exprs} FROM {_quote_ident(table)}) TO STDOUT", buf
    )
    return columns, buf.getvalue()


def dump_compare_db(
    path: Path | str | None = None,
    months: int = 12,
    today: date | None = None,
) -> Path:
    """Write a COPY script of the current database's compare snapshot."""
    path = Path(path) if path else LIVE_DUMP_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    cutoff = assignment_cutoff(months, today)
    user_table = get_user_model()._meta.db_table
    tables = [t for t in _full_tables() if t != user_table]
    assignment_table = Assignment._meta.db_table

    with connection.cursor() as cursor, path.open("w", encoding="utf-8") as out:
        out.write(
            "-- Generated by dump_compare_db. Names, emails, and passwords "
            "are anonymized.\n"
        )
        out.write(
            f"-- Assignments on or after {cutoff.isoformat()} ({months} months).\n"
        )
        out.write("SET session_replication_role = replica;\n\n")

        columns, data = _user_copy(cursor)
        _write_copy(out, user_table, columns, data)

        for table in tables:
            columns = _table_columns(cursor, table)
            _write_copy(out, table, columns, _copy_select(cursor, table, columns))

        columns = _table_columns(cursor, assignment_table)
        where = f"WHERE assigned_at >= '{cutoff.isoformat()}'::timestamp"
        _write_copy(
            out,
            assignment_table,
            columns,
            _copy_select(cursor, assignment_table, columns, where),
        )

        for table in [user_table, *tables, assignment_table]:
            for column in _serial_columns(cursor, table):
                out.write(
                    "SELECT setval(\n"
                    f"  pg_get_serial_sequence('{table}', '{column}'),\n"
                    f"  COALESCE((SELECT MAX({_quote_ident(column)}) "
                    f"FROM {_quote_ident(table)}), 1)\n"
                    ");\n"
                )
        out.write("\nSET session_replication_role = origin;\n")

    return path


def _flush_sql(cursor, buf: list[str]):
    cleaned = []
    for line in buf:
        stripped = line.strip()
        if not stripped or stripped.startswith("--"):
            continue
        cleaned.append(line)
    text = "".join(cleaned).strip()
    if not text:
        return
    for raw in text.split(";"):
        stmt = raw.strip()
        if not stmt:
            continue
        cursor.execute(stmt)


def load_compare_dump(path: Path | str | None = None) -> Path:
    """Load a dump_compare_db SQL file into the current database."""
    path = Path(path) if path else LIVE_DUMP_PATH
    if not path.is_file():
        raise FileNotFoundError(
            f"{path} is missing. Run: python manage.py dump_compare_db"
        )

    lines = path.read_text(encoding="utf-8").splitlines(keepends=True)
    stmt_buf: list[str] = []
    with connection.cursor() as cursor:
        i = 0
        while i < len(lines):
            line = lines[i]
            stripped = line.strip()
            if stripped.upper().startswith("COPY ") and "FROM stdin" in stripped:
                _flush_sql(cursor, stmt_buf)
                stmt_buf = []
                copy_sql = stripped if stripped.endswith(";") else stripped + ";"
                i += 1
                data = []
                while i < len(lines) and lines[i].rstrip("\r\n") != "\\.":
                    data.append(lines[i])
                    i += 1
                if i >= len(lines):
                    raise ValueError(f"{path}: unterminated COPY block")
                i += 1
                cursor.copy_expert(copy_sql, StringIO("".join(data)))
            else:
                stmt_buf.append(line)
                i += 1
        _flush_sql(cursor, stmt_buf)
    return path
